#!/usr/bin/env python3
"""Render the backup / restore / Flowable-bootstrap scripts into the Helm chart (slice 9C).

Helm cannot read files outside the chart directory, so the ConfigMap
`deploy/helm/sutraerp/templates/data/backup-scripts.yaml` embeds copies of
deploy/backup/{lib.sh,sutra-backup.sh,sutra-restore.sh,roles.sql} and deploy/flowable/init-db.sh.
Run from anywhere after editing a script; `--check` writes nothing and exits 1 when the committed
template is stale (Data platform CI step).
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "deploy/helm/sutraerp/templates/data/backup-scripts.yaml"
FILES = [
    ("lib.sh", ROOT / "deploy/backup/lib.sh"),
    ("sutra-backup.sh", ROOT / "deploy/backup/sutra-backup.sh"),
    ("sutra-restore.sh", ROOT / "deploy/backup/sutra-restore.sh"),
    ("roles.sql", ROOT / "deploy/backup/roles.sql"),
    ("init-db.sh", ROOT / "deploy/flowable/init-db.sh"),
]


def render() -> str:
    out = [
        "{{- /* 9C: GENERATED by deploy/backup/gen-chart.py from deploy/backup/* and",
        "deploy/flowable/init-db.sh. Do not edit; re-run the generator. */ -}}",
        "{{- if or .Values.backup.enabled (and .Values.flowable.enabled .Values.flowable.bundled .Values.flowable.initDb.enabled) }}",
        "apiVersion: v1",
        "kind: ConfigMap",
        "metadata:",
        '  name: {{ include "sutraerp.data.name" (dict "root" . "component" "backup-scripts") }}',
        "  labels:",
        '    {{- include "sutraerp.data.labels" (dict "root" . "component" "backup") | nindent 4 }}',
        "data:",
    ]
    for key, path in FILES:
        text = path.read_text()
        if "{{" in text or "}}" in text:
            sys.exit(f"{path}: contains '{{{{' or '}}}}' (Helm template syntax); rewrite it")
        if "\t" in text:
            sys.exit(f"{path}: contains a tab (YAML block scalars cannot hold it safely)")
        out.append(f"  {key}: |")
        for line in text.rstrip("\n").split("\n"):
            out.append(("    " + line) if line else "")
    out.append("{{- end }}")
    return "\n".join(out) + "\n"


def main() -> int:
    want = render()
    if "--check" in sys.argv:
        have = OUT.read_text() if OUT.exists() else ""
        if have != want:
            print(f"{OUT.relative_to(ROOT)} is stale: run deploy/backup/gen-chart.py", file=sys.stderr)
            return 1
        print(f"ok chart scripts ({len(FILES)} files embedded, up to date)")
        return 0
    OUT.write_text(want)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

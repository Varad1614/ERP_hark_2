// Part 1 · Stage 3 (S3-config): hash-based CSP for the SPA's inline bootstrap scripts.
//
// React Router (SPA mode) writes its hydration context and module bootstrap as inline <script>
// elements into build/client/*.html. Instead of `script-src 'unsafe-inline'` (SEC-9D-011), the web
// image allows exactly those scripts by SHA-256: this runs after `pnpm build` and writes an nginx
// snippet that sets $sutra_csp_script_hashes, which the Content-Security-Policy header uses
// (deploy/docker/nginx.conf, deploy/helm/sutraerp/templates/web/configmap.yaml).
//
//   node deploy/docker/csp-hashes.mjs <build/client> <out.conf>
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [dir, out] = process.argv.slice(2);
if (!dir || !out) {
  console.error("usage: csp-hashes.mjs <build/client> <out.conf>");
  process.exit(2);
}
const hashes = new Set();
const pages = readdirSync(dir).filter((f) => f.endsWith(".html"));
if (pages.length === 0) {
  console.error(`csp-hashes: no .html files in ${dir}`);
  process.exit(1);
}
for (const page of pages) {
  const html = readFileSync(join(dir, page), "utf8");
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    if (/\bsrc\s*=/i.test(m[1]) || m[2].length === 0) continue;
    hashes.add(`'sha256-${createHash("sha256").update(m[2], "utf8").digest("base64")}'`);
  }
  if (/<[a-z][^>]*\son[a-z]+\s*=/i.test(html.replace(/<script\b[\s\S]*?<\/script>/gi, ""))) {
    console.error(`csp-hashes: ${page} has an inline event handler attribute; CSP would block it`);
    process.exit(1);
  }
}
const list = [...hashes].sort().join(" ");
writeFileSync(
  out,
  `# Generated by deploy/docker/csp-hashes.mjs at image build: inline scripts of ${pages.join(", ")}.\n` +
    `set $sutra_csp_script_hashes "${list}";\n`,
);
console.log(`csp-hashes: ${hashes.size} inline script(s) in ${pages.length} page(s) → ${out}`);

# ---------------- Helm embed: the chart cannot read files outside its directory, so the rules,
# dashboards and the lgtm Prometheus config are embedded (base64) as named templates.
import base64
def b64(path):
    return base64.b64encode(open(path, "rb").read()).decode()
chart_tpl = "../helm/sutraerp/templates/observability/_generated.tpl"
parts = ["{{- /* GENERATED by deploy/observability/gen.py from deploy/observability/{alerts,dashboards}. Do not edit; CI fails when stale. */ -}}"]
parts.append('{{- define "sutraerp.observability.rules" -}}' + b64("alerts/sutra.rules.yaml") + "{{- end -}}")
names = []
for f in sorted(os.listdir("dashboards")):
    if f.endswith(".json"):
        n = f[:-5]
        names.append(n)
        parts.append('{{- define "sutraerp.observability.dashboard.' + n + '" -}}' + b64("dashboards/" + f) + "{{- end -}}")
parts.append('{{- define "sutraerp.observability.dashboards" -}}' + ",".join(names) + "{{- end -}}")
open(chart_tpl, "w").write("\n".join(parts) + "\n")
print("chart embed ok", names)

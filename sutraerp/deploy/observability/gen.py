DS={"prom":{"type":"prometheus","uid":"${DS_PROMETHEUS}"},"loki":{"type":"loki","uid":"${DS_LOKI}"},"tempo":{"type":"tempo","uid":"${DS_TEMPO}"}}
def templating(extra=()):
    l=[{"name":"DS_PROMETHEUS","label":"Prometheus","type":"datasource","query":"prometheus","current":{},"hide":0},
       {"name":"DS_LOKI","label":"Loki","type":"datasource","query":"loki","current":{},"hide":0},
       {"name":"DS_TEMPO","label":"Tempo","type":"datasource","query":"tempo","current":{},"hide":0}]
    l.extend(extra)
    return {"list":l}
pid=[0]
def panel(title, kind, targets, x, y, w=12, h=8, unit=None, ds="prom", desc=None):
    pid[0]+=1
    p={"id":pid[0],"title":title,"type":kind,"datasource":DS[ds],"gridPos":{"x":x,"y":y,"w":w,"h":h},"targets":[]}
    for i,tg in enumerate(targets):
        if ds=="prom":
            p["targets"].append({"refId":chr(65+i),"datasource":DS[ds],"expr":tg[0],"legendFormat":tg[1]})
        elif ds=="loki":
            p["targets"].append({"refId":chr(65+i),"datasource":DS[ds],"expr":tg[0]})
        else:
            p["targets"].append({"refId":chr(65+i),"datasource":DS[ds],"queryType":"traceql","query":tg[0],"limit":20})
    if unit: p["fieldConfig"]={"defaults":{"unit":unit},"overrides":[]}
    if desc: p["description"]=desc
    return p

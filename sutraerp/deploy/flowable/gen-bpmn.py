#!/usr/bin/env python3
"""Generate one Flowable BPMN 2.0 process per approval key (Batch 9 · 9C, contract §7).

Keys = every `pub const NAME: &str = "<domain>.<process>"` inside `pub mod process { … }` of
`modules/*/src/shared/approval.rs` and `modules/platform/src/dataimport/mod.rs`. Outputs (run from `sutraerp/`):

* `deploy/flowable/processes/<key>.bpmn20.xml` — start → exclusive gateway on `${autoApprove}`
  → (true) end `approved` | (default) user task `decide` (candidate group `sutra:approvers`) → end
  `decided`. Process id = the key verbatim.
* the `PROCESS_KEYS` block of `modules/platform/src/workflow_flowable.rs` (between the
  `BEGIN GENERATED PROCESS KEYS` / `END GENERATED PROCESS KEYS` markers). The adapter deploys
  `sutra_platform::workflow_flowable::bpmn_xml(key)` for each key, which renders the same
  template as this script (`db_b9c` asserts byte equality with the committed files).

`--check` writes nothing and exits 1 when a key has no BPMN file, a file has no key, a file's
content drifted, or the Rust key list differs (CI step of the Data platform job).
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "deploy" / "flowable" / "processes"
RUST = ROOT / "modules" / "platform" / "src" / "workflow_flowable.rs"
BEGIN = "// BEGIN GENERATED PROCESS KEYS (deploy/flowable/gen-bpmn.py)"
END = "// END GENERATED PROCESS KEYS"

# Must stay byte-identical to `BPMN_TEMPLATE` in modules/platform/src/workflow_flowable.rs.
TEMPLATE = """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by deploy/flowable/gen-bpmn.py from the approval keys. Do not edit. -->
<definitions xmlns="http://www.omg.org/spec/BPMN/20100524/MODEL"
             xmlns:flowable="http://flowable.org/bpmn"
             xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
             targetNamespace="urn:sutraerp:approval">
  <process id="{key}" name="{key}" isExecutable="true">
    <startEvent id="start"/>
    <sequenceFlow id="toGateway" sourceRef="start" targetRef="autoApproveGateway"/>
    <exclusiveGateway id="autoApproveGateway" default="toDecide"/>
    <sequenceFlow id="toApproved" sourceRef="autoApproveGateway" targetRef="approved">
      <conditionExpression xsi:type="tFormalExpression"><![CDATA[${autoApprove}]]></conditionExpression>
    </sequenceFlow>
    <sequenceFlow id="toDecide" sourceRef="autoApproveGateway" targetRef="decide"/>
    <userTask id="decide" name="Decide" flowable:candidateGroups="sutra:approvers"/>
    <sequenceFlow id="toDecided" sourceRef="decide" targetRef="decided"/>
    <endEvent id="approved" name="approved"/>
    <endEvent id="decided" name="decided"/>
  </process>
</definitions>
"""

KEY_RE = re.compile(r'pub const [A-Z0-9_]+\s*:\s*&str\s*=\s*"([a-z]+\.[a-z0-9_]+)"\s*;')


def keys():
    found = []
    # Every module's shared approval keys, plus modules whose process keys live with their
    # feature (the data import's commit approval, DEF-P2-CAP-004).
    sources = sorted(ROOT.glob("modules/*/src/shared/approval.rs")) + [
        ROOT / "modules/platform/src/dataimport/mod.rs",
    ]
    for f in sources:
        text = f.read_text(encoding="utf-8")
        m = re.search(r"pub mod process \{(.*?)\n\}", text, re.S)
        if not m:
            continue
        found.extend(KEY_RE.findall(m.group(1)))
    dup = sorted({k for k in found if found.count(k) > 1})
    if dup:
        sys.exit(f"duplicate approval keys: {dup}")
    return sorted(found)


def render(key):
    return TEMPLATE.replace("{key}", key)


def rust_block(ks):
    lines = [BEGIN, "pub const PROCESS_KEYS: &[&str] = &["]
    lines += [f'    "{k}",' for k in ks]
    lines += ["];", END]
    return "\n".join(lines)


def rust_keys(text):
    m = re.search(re.escape(BEGIN) + r"(.*?)" + re.escape(END), text, re.S)
    if not m:
        return None
    return sorted(re.findall(r'"([a-z]+\.[a-z0-9_]+)"', m.group(1)))


def main():
    check = "--check" in sys.argv
    ks = keys()
    if not ks:
        sys.exit("no approval keys found")
    problems = []
    existing = {p.name[: -len(".bpmn20.xml")] for p in OUT.glob("*.bpmn20.xml")} if OUT.exists() else set()
    for k in ks:
        path = OUT / f"{k}.bpmn20.xml"
        if check:
            if not path.exists():
                problems.append(f"missing BPMN for approval key {k}: {path.relative_to(ROOT)}")
            elif path.read_text(encoding="utf-8") != render(k):
                problems.append(f"BPMN drifted: {path.relative_to(ROOT)}")
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(render(k), encoding="utf-8")
    for stale in sorted(existing - set(ks)):
        path = OUT / f"{stale}.bpmn20.xml"
        if check:
            problems.append(f"BPMN without approval key: {path.relative_to(ROOT)}")
        else:
            path.unlink()
    text = RUST.read_text(encoding="utf-8")
    if rust_keys(text) != ks:
        if check:
            problems.append("PROCESS_KEYS in modules/platform/src/workflow_flowable.rs is stale")
        else:
            start = text.index(BEGIN)
            end = text.index(END) + len(END)
            RUST.write_text(text[:start] + rust_block(ks) + text[end:], encoding="utf-8")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        print("run: python3 deploy/flowable/gen-bpmn.py", file=sys.stderr)
        sys.exit(1)
    print(f"ok bpmn {len(ks)} approval processes" + (" (checked)" if check else " (generated)"))


if __name__ == "__main__":
    main()

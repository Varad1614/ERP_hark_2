#!/usr/bin/env node
// Golden-vector generator for logic ported from HeyPuter/everything (MIT).
//
// Each spec in ./specs runs the ORIGINAL pure JS function from Everything, pinned to the commit
// in pin.json, over a deterministic set of inputs, and writes inputs + outputs as a JSON fixture
// that the Rust port's tests replay. `--check` regenerates in memory and fails when a committed
// fixture differs (spec changed without regenerating, or the pin moved).
//
//   node tools/golden/generate.mjs            # write fixtures
//   node tools/golden/generate.mjs --check    # CI drift check
//   EVERYTHING_SRC=/path/to/everything node tools/golden/generate.mjs   # reuse a checkout
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..'); // sutraerp/
const pin = JSON.parse(readFileSync(join(here, 'pin.json'), 'utf8'));
const check = process.argv.includes('--check');

const specs = [];
for (const f of readdirSync(join(here, 'specs')).filter((f) => f.endsWith('.mjs') && !f.startsWith('_')).sort()) {
  specs.push((await import(pathToFileURL(join(here, 'specs', f)).href)).default);
}

function checkout() {
  if (process.env.EVERYTHING_SRC) return resolve(process.env.EVERYTHING_SRC);
  const dir = join(root, '.cache', 'everything');
  const git = (...a) => execFileSync('git', a, { cwd: dir, stdio: ['ignore', 'ignore', 'inherit'] });
  if (!existsSync(join(dir, '.git'))) {
    mkdirSync(dir, { recursive: true });
    git('init', '-q');
    git('remote', 'add', 'origin', pin.repo);
    git('config', 'core.sparseCheckout', 'true');
  }
  const paths = [...new Set(specs.flatMap((s) => s.paths))];
  writeFileSync(join(dir, '.git', 'info', 'sparse-checkout'), paths.map((p) => `/${p}\n`).join(''));
  git('fetch', '-q', '--depth', '1', '--filter=blob:none', 'origin', pin.commit);
  git('checkout', '-q', '--force', pin.commit);
  return dir;
}

const src = checkout();
let drift = 0;
for (const spec of specs) {
  const mod = await import(pathToFileURL(join(src, spec.module)).href);
  const cases = spec.cases().map((input) => ({ input, expected: spec.run(mod, input) }));
  const head = {
    source: `${pin.repo.replace(/\.git$/, '')}/blob/${pin.commit}/${spec.module}`,
    function: spec.fn,
    license: pin.license,
    note: 'Generated by tools/golden/generate.mjs. Do not edit by hand.',
  };
  // One case per line: readable diffs, small files.
  const body = cases.map((c) => `  ${JSON.stringify(c)}`).join(',\n');
  const text = `${JSON.stringify(head, null, 1).replace(/\n}$/, '')},\n "cases": [\n${body}\n ]\n}\n`;
  const out = join(root, spec.out);
  if (check) {
    const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
    if (current !== text) {
      drift++;
      console.error(`golden drift: ${spec.out} (run: node tools/golden/generate.mjs)`);
    } else {
      console.log(`ok    ${spec.out} (${cases.length} cases)`);
    }
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, text);
    console.log(`wrote ${spec.out} (${cases.length} cases)`);
  }
}
process.exit(drift ? 1 : 0);

//! Flowable OSS REST realisation of [`WorkflowPort`] (ADR-L5-0023 / ADR-L5-0042) — **owned by
//! slice 9C** (`docs/batch9-contracts.md` §7). Pinned runtime: `flowable/flowable-rest:8.0.0`.
//!
//! * `start_process` → `POST {url}/service/runtime/process-instances` with
//!   `processDefinitionKey`, `businessKey` and the variables `sutraTenantId`,
//!   `sutraInstitutionId`, `autoApprove` + the caller's variables (no Flowable tenancy: the tenant
//!   travels as a variable and is re-checked on every task call). A live instance with the same
//!   key + business key of the same tenant is reused, so a retried command never starts a
//!   second process.
//! * `autoApprove` rule (Part 1, DEF-X-001): always `false` (the BPMN waits at `decide` for the
//!   domain decision endpoint) unless the adapter was built with `allow_auto_approve`
//!   (`SUTRA_FLOWABLE_AUTO_APPROVE=true`, development / test only — refused in production) **and**
//!   the caller's variables contain `"autoApprove": true`.
//! * `complete_task` → `POST runtime/tasks/{id}` (`action=complete`) after checking the task's
//!   process belongs to the caller's tenant; `signal` → every execution of the instance
//!   subscribed to the signal gets `PUT runtime/executions/{id}` (`action=signalEventReceived`).
//! * BPMN: one process per approval key ([`PROCESS_KEYS`], generated by
//!   `deploy/flowable/gen-bpmn.py`), rendered by [`bpmn_xml`] (byte-identical to
//!   `deploy/flowable/processes/<key>.bpmn20.xml`) and deployed when missing on first use /
//!   first decision-sync tick when `SUTRA_FLOWABLE_DEPLOY_ON_START=true`.
//! * Errors: transport failures, 5xx and 401/403 → `KernelError::Unavailable` (503 problem);
//!   other non-success answers → `KernelError::Internal`; unknown task → `NotFound`.
//! * Decision sync ([`DecisionSync`], job `workflow_decision_sync`): outbox events whose `data`
//!   carries the `processInstanceId` of a live Flowable instance and a decided `toStatus`
//!   complete that instance's `decide` task with `outcome = toStatus`, so the domain decision
//!   endpoints stay unchanged.
//! * Telemetry: spans `sutra.workflow.<op>`, counter `sutra_workflow_calls_total{op,outcome}`.
//!
//! Selected by `SUTRA_WORKFLOW=flowable`; the no-op adapter stays the default.


/// Must stay byte-identical to `TEMPLATE` in `deploy/flowable/gen-bpmn.py`.
const BPMN_TEMPLATE: &str = r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by deploy/flowable/gen-bpmn.py from the approval keys. Do not edit. -->
<definitions xmlns="http://www.omg.org/spec/BPMN/20100524/MODEL"
             xmlns:flowable="http://flowable.org/bpmn"
             xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
             targetNamespace="urn:sutraerp:approval">
  <process id="{key}" name="{key}" isExecutable="true">
    <startEvent id="start"/>
    <sequenceFlow id="toGateway" sourceRef="start" targetRef="autoApproveGateway"/>
    <exclusiveGateway id="autoApproveGateway" default="toDecide"/>
    <sequenceFlow id="toApproved" sourceRef="autoApproveGateway" targetRef="approved">
      <conditionExpression xsi:type="tFormalExpression"><![CDATA[${autoApprove}]]></conditionExpression>
    </sequenceFlow>
    <sequenceFlow id="toDecide" sourceRef="autoApproveGateway" targetRef="decide"/>
    <userTask id="decide" name="Decide" flowable:candidateGroups="sutra:approvers"/>
    <sequenceFlow id="toDecided" sourceRef="decide" targetRef="decided"/>
    <endEvent id="approved" name="approved"/>
    <endEvent id="decided" name="decided"/>
  </process>
</definitions>
"#;

/// BPMN 2.0 XML of one approval process (`deploy/flowable/processes/<key>.bpmn20.xml`).
pub fn bpmn_xml(key: &str) -> String {
    BPMN_TEMPLATE.replace("{key}", key)
}

/// Adapter settings (`Config::hardening.workflow`).
#[derive(Clone)]
pub struct FlowableSettings {
    /// `http://host:8080/flowable-rest` (the REST API lives under `/service`).
    pub url: String,
    pub user: String,
    pub password: Option<String>,
    pub timeout: Duration,
    pub deploy_on_start: bool,
    /// Part 1 (DEF-X-001): honour a caller's `autoApprove: true` (dev / test only; production
    /// refuses `SUTRA_FLOWABLE_AUTO_APPROVE=true`). Default false.
    pub allow_auto_approve: bool,
}

impl std::fmt::Debug for FlowableSettings {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("FlowableSettings")
            .field("url", &self.url)
            .field("user", &self.user)
            .field("timeout", &self.timeout)
            .field("deploy_on_start", &self.deploy_on_start)
            .field("allow_auto_approve", &self.allow_auto_approve)
            .finish_non_exhaustive()
    }
}

fn record(op: &'static str, ok: bool) {
    let outcome = if ok { "ok" } else { "error" };
    metrics::counter!("sutra_workflow_calls_total", "op" => op, "outcome" => outcome).increment(1);
}

fn unavailable(e: impl std::fmt::Display) -> KernelError {
    KernelError::Unavailable(format!("flowable: {e}"))
}

/// Flowable REST variables (`[{name, type, value}]`) from the port's JSON variables.
pub fn rest_variables(vars: &BTreeMap<String, serde_json::Value>) -> Vec<serde_json::Value> {
    vars.iter()
        .filter_map(|(name, v)| {
            let (ty, value) = match v {
                serde_json::Value::Null => return None,
                serde_json::Value::Bool(_) => ("boolean", v.clone()),
                serde_json::Value::Number(n) if n.is_i64() || n.is_u64() => ("long", v.clone()),
                serde_json::Value::Number(_) => ("double", v.clone()),
                serde_json::Value::String(_) => ("string", v.clone()),
                other => ("string", serde_json::Value::String(other.to_string())),
            };
            Some(serde_json::json!({ "name": name, "type": ty, "value": value }))
        })
        .collect()
}

/// Caller variables + the scope / `autoApprove` variables the BPMN needs (pure).
pub fn start_variables(
    scope: &ExecutionScope,
    caller: &BTreeMap<String, serde_json::Value>,
    allow_auto_approve: bool,
) -> BTreeMap<String, serde_json::Value> {
    let mut vars = caller.clone();
    // Part 1 (DEF-X-001): human decision unless auto-approval is explicitly allowed AND asked for.
    let auto = allow_auto_approve
        && matches!(
            caller.get("autoApprove"),
            Some(serde_json::Value::Bool(true))
        );
    vars.insert("autoApprove".into(), serde_json::Value::Bool(auto));
    vars.insert(
        "sutraTenantId".into(),
        serde_json::Value::String(scope.tenant_id.as_uuid().to_string()),
    );
    match scope.institution_id {
        Some(i) => {
            vars.insert(
                "sutraInstitutionId".into(),
                serde_json::Value::String(i.as_uuid().to_string()),
            );
        }
        None => {
            vars.remove("sutraInstitutionId");
        }
    }
    vars
}

/// `multipart/form-data` body with one BPMN file (reqwest's multipart feature is not enabled).
fn multipart_body(boundary: &str, file_name: &str, xml: &str) -> String {
    format!(
        "--{boundary}\r\nContent-Disposition: form-data; name=\"file\"; filename=\"{file_name}\"\r\n\
         Content-Type: text/xml\r\n\r\n{xml}\r\n--{boundary}--\r\n"
    )
}

/// Percent-encodes one query value.
fn qv(v: &str) -> String {
    url::form_urlencoded::byte_serialize(v.as_bytes()).collect()
}

/// The Flowable REST adapter.
pub struct FlowableWorkflowAdapter {
    http: reqwest::Client,
    settings: FlowableSettings,
    deployed: OnceCell<usize>,
}

impl std::fmt::Debug for FlowableWorkflowAdapter {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("FlowableWorkflowAdapter")
            .field("settings", &self.settings)
            .finish_non_exhaustive()
    }
}

impl FlowableWorkflowAdapter {
    /// Builds the HTTP client; does not connect.
    pub fn new(settings: FlowableSettings) -> Result<Self, String> {
        url::Url::parse(&settings.url).map_err(|e| format!("invalid SUTRA_FLOWABLE_URL: {e}"))?;
        let http = crate::tls::with_extra_roots(
            reqwest::Client::builder()
                .timeout(settings.timeout)
                .connect_timeout(settings.timeout.min(Duration::from_secs(5))),
        )?
        .build()
        .map_err(|e| format!("flowable client: {e}"))?;
        Ok(Self {
            http,
            settings,
            deployed: OnceCell::new(),
        })
    }

    pub fn settings(&self) -> &FlowableSettings {
        &self.settings
    }

    fn req(&self, method: reqwest::Method, path: &str) -> reqwest::RequestBuilder {
        let url = format!(
            "{}/service/{}",
            self.settings.url.trim_end_matches('/'),
            path.trim_start_matches('/')
        );
        self.http
            .request(method, url)
            .basic_auth(&self.settings.user, self.settings.password.as_deref())
    }

    async fn send(
        &self,
        rb: reqwest::RequestBuilder,
    ) -> Result<(reqwest::StatusCode, serde_json::Value), KernelError> {
        let res = rb.send().await.map_err(unavailable)?;
        let status = res.status();
        let text = res.text().await.map_err(unavailable)?;
        let body = if text.is_empty() {
            serde_json::Value::Null
        } else {
            serde_json::from_str(&text).unwrap_or(serde_json::Value::String(text))
        };
        if status.is_server_error() {
            return Err(unavailable(format!("{status}: {body}")));
        }
        Ok((status, body))
    }

    fn fail(what: &str, status: reqwest::StatusCode, body: &serde_json::Value) -> KernelError {
        if status == reqwest::StatusCode::UNAUTHORIZED || status == reqwest::StatusCode::FORBIDDEN {
            return unavailable(format!(
                "{what}: {status} (check SUTRA_FLOWABLE_USER / SUTRA_FLOWABLE_PASSWORD)"
            ));
        }
        KernelError::internal_msg(format!("flowable {what}: {status}: {body}"))
    }

    async fn get_json(&self, path: &str) -> Result<Option<serde_json::Value>, KernelError> {
        let (status, body) = self.send(self.req(reqwest::Method::GET, path)).await?;
        if status == reqwest::StatusCode::NOT_FOUND {
            return Ok(None);
        }
        if !status.is_success() {
            return Err(Self::fail(path, status, &body));
        }
        Ok(Some(body))
    }

    fn data_array(body: &serde_json::Value) -> Vec<serde_json::Value> {
        body.get("data")
            .and_then(|d| d.as_array())
            .cloned()
            .unwrap_or_default()
    }

    /// Engine reachable (`GET management/engine`).
    pub async fn ping(&self) -> Result<(), KernelError> {
        self.get_json("management/engine")
            .await?
            .map(|_| ())
            .ok_or_else(|| unavailable("management/engine not found"))
    }

    /// Keys of every deployed process definition (latest versions).
    pub async fn deployed_keys(&self) -> Result<BTreeSet<String>, KernelError> {
        let mut keys = BTreeSet::new();
        let mut start = 0usize;
        loop {
            let body = self
                .get_json(&format!(
                    "repository/process-definitions?latest=true&size=500&start={start}"
                ))
                .await?
                .unwrap_or_default();
            let page = Self::data_array(&body);
            for d in &page {
                if let Some(k) = d.get("key").and_then(|k| k.as_str()) {
                    keys.insert(k.to_owned());
                }
            }
            let total = body.get("total").and_then(|t| t.as_u64()).unwrap_or(0) as usize;
            start += page.len();
            if page.is_empty() || start >= total {
                break;
            }
        }
        Ok(keys)
    }

    /// Deploys one BPMN document as deployment `<key>`.
    pub async fn deploy(&self, key: &str) -> Result<(), KernelError> {
        let boundary = format!("sutra-{}", sutra_kernel::id::new_v7().simple());
        let body = multipart_body(&boundary, &format!("{key}.bpmn20.xml"), &bpmn_xml(key));
        let rb = self
            .req(
                reqwest::Method::POST,
                &format!("repository/deployments?deploymentName={}", qv(key)),
            )
            .header(
                reqwest::header::CONTENT_TYPE,
                format!("multipart/form-data; boundary={boundary}"),
            )
            .body(body);
        let (status, resp) = self.send(rb).await?;
        let ok = status.is_success();
        record("deploy", ok);
        if ok {
            Ok(())
        } else {
            Err(Self::fail("deploy", status, &resp))
        }
    }

    /// Deploys every key of `keys` that has no definition yet; returns how many.
    pub async fn deploy_missing(&self, keys: &[&str]) -> Result<usize, KernelError> {
        let have = self.deployed_keys().await?;
        let mut n = 0;
        for k in keys.iter().filter(|k| !have.contains(**k)) {
            self.deploy(k).await?;
            n += 1;
        }
        if n > 0 {
            tracing::info!(
                deployed = n,
                "flowable: deployed missing approval processes"
            );
        }
        Ok(n)
    }

    /// Deploy-on-start, once per process (retried on the next call after a failure).
    pub async fn ensure_deployed(&self) -> Result<(), KernelError> {
        if !self.settings.deploy_on_start {
            return Ok(());
        }
        self.deployed
            .get_or_try_init(|| async {
                self.deploy_missing(PROCESS_KEYS)
                    .instrument(tracing::info_span!("sutra.workflow.deploy"))
                    .await
            })
            .await
            .map(|_| ())
    }

    /// `sutraTenantId` of a running process instance (`None` when the instance is gone).
    async fn instance_tenant(
        &self,
        process_instance_id: &str,
    ) -> Result<Option<String>, KernelError> {
        let body = self
            .get_json(&format!(
                "runtime/process-instances/{}/variables/sutraTenantId",
                qv(process_instance_id)
            ))
            .await?;
        Ok(body.and_then(|b| b.get("value").and_then(|v| v.as_str()).map(str::to_owned)))
    }

    async fn ensure_tenant(
        &self,
        scope: &ExecutionScope,
        process_instance_id: &str,
    ) -> Result<(), KernelError> {
        match self.instance_tenant(process_instance_id).await? {
            Some(t) if t == scope.tenant_id.as_uuid().to_string() => Ok(()),
            Some(_) => Err(KernelError::Forbidden(
                "workflow instance belongs to another tenant".into(),
            )),
            None => Err(KernelError::NotFound {
                entity: "workflow process instance",
            }),
        }
    }

    async fn find_live(
        &self,
        key: &str,
        business_key: &str,
        tenant: &str,
    ) -> Result<Option<String>, KernelError> {
        let path = format!(
            "runtime/process-instances?processDefinitionKey={}&businessKey={}",
            qv(key),
            qv(business_key)
        );
        let body = self.get_json(&path).await?.unwrap_or_default();
        for inst in Self::data_array(&body) {
            let Some(id) = inst.get("id").and_then(|i| i.as_str()) else {
                continue;
            };
            if self.instance_tenant(id).await?.as_deref() == Some(tenant) {
                return Ok(Some(id.to_owned()));
            }
        }
        Ok(None)
    }

    async fn start_inner(
        &self,
        scope: &ExecutionScope,
        req: StartProcess,
    ) -> Result<ProcessInstanceRef, KernelError> {
        self.ensure_deployed().await?;
        let tenant = scope.tenant_id.as_uuid().to_string();
        if let Some(id) = self
            .find_live(&req.process_definition_key, &req.business_key, &tenant)
            .await?
        {
            return Ok(ProcessInstanceRef {
                process_definition_key: req.process_definition_key,
                process_instance_id: id,
                business_key: req.business_key,
            });
        }
        let vars = start_variables(scope, &req.variables, self.settings.allow_auto_approve);
        let body = serde_json::json!({
            "processDefinitionKey": req.process_definition_key,
            "businessKey": req.business_key,
            "variables": rest_variables(&vars),
            "returnVariables": false,
        });
        let (status, resp) = self
            .send(
                self.req(reqwest::Method::POST, "runtime/process-instances")
                    .json(&body),
            )
            .await?;
        if !status.is_success() {
            return Err(Self::fail("start process", status, &resp));
        }
        let id = resp
            .get("id")
            .and_then(|i| i.as_str())
            .ok_or_else(|| KernelError::internal_msg("flowable start: no process instance id"))?;
        Ok(ProcessInstanceRef {
            process_definition_key: req.process_definition_key,
            process_instance_id: id.to_owned(),
            business_key: req.business_key,
        })
    }

    async fn complete_inner(
        &self,
        scope: &ExecutionScope,
        task_id: &str,
        variables: BTreeMap<String, serde_json::Value>,
    ) -> Result<(), KernelError> {
        let not_found = || KernelError::NotFound {
            entity: "workflow task",
        };
        let task = self
            .get_json(&format!("runtime/tasks/{}", qv(task_id)))
            .await?
            .ok_or_else(not_found)?;
        let pid = task
            .get("processInstanceId")
            .and_then(|p| p.as_str())
            .ok_or_else(not_found)?;
        self.ensure_tenant(scope, pid).await?;
        let body = serde_json::json!({
            "action": "complete",
            "variables": rest_variables(&variables),
        });
        let (status, resp) = self
            .send(
                self.req(
                    reqwest::Method::POST,
                    &format!("runtime/tasks/{}", qv(task_id)),
                )
                .json(&body),
            )
            .await?;
        if status == reqwest::StatusCode::NOT_FOUND {
            return Err(not_found());
        }
        if !status.is_success() {
            return Err(Self::fail("complete task", status, &resp));
        }
        Ok(())
    }

    async fn signal_inner(
        &self,
        scope: &ExecutionScope,
        process_instance_id: &str,
        signal: &str,
    ) -> Result<(), KernelError> {
        self.ensure_tenant(scope, process_instance_id).await?;
        let path = format!(
            "runtime/executions?processInstanceId={}&signalEventSubscriptionName={}",
            qv(process_instance_id),
            qv(signal)
        );
        let body = self.get_json(&path).await?.unwrap_or_default();
        let executions = Self::data_array(&body);
        if executions.is_empty() {
            return Err(KernelError::NotFound {
                entity: "workflow signal subscription",
            });
        }
        for e in executions {
            let Some(id) = e.get("id").and_then(|i| i.as_str()) else {
                continue;
            };
            let body = serde_json::json!({ "action": "signalEventReceived", "signalName": signal });
            let (status, resp) = self
                .send(
                    self.req(
                        reqwest::Method::PUT,
                        &format!("runtime/executions/{}", qv(id)),
                    )
                    .json(&body),
                )
                .await?;
            if !status.is_success() {
                return Err(Self::fail("signal", status, &resp));
            }
        }
        Ok(())
    }

    /// Completes the open `decide` task of `process_instance_id` with `outcome`. `Ok(false)` when
    /// the instance has no open decision (auto-approved, already decided, or unknown).
    pub async fn complete_decision(
        &self,
        scope: &ExecutionScope,
        process_instance_id: &str,
        outcome: &str,
    ) -> Result<bool, KernelError> {
        let r = async {
            let path = format!(
                "runtime/tasks?processInstanceId={}&taskDefinitionKey={DECIDE_TASK}",
                qv(process_instance_id)
            );
            let body = self.get_json(&path).await?.unwrap_or_default();
            let tasks = Self::data_array(&body);
            let Some(task_id) = tasks
                .first()
                .and_then(|t| t.get("id"))
                .and_then(|i| i.as_str())
                .map(str::to_owned)
            else {
                return Ok(false);
            };
            let mut vars = BTreeMap::new();
            vars.insert(
                "outcome".to_owned(),
                serde_json::Value::String(outcome.to_owned()),
            );
            self.complete_inner(scope, &task_id, vars).await?;
            Ok(true)
        }
        .instrument(tracing::info_span!("sutra.workflow.decide"))
        .await;
        record("decide", r.is_ok());
        r
    }

    /// History of one instance: `Some(true)` = ended, `Some(false)` = running, `None` = unknown.
    pub async fn instance_ended(
        &self,
        process_instance_id: &str,
    ) -> Result<Option<bool>, KernelError> {
        let body = self
            .get_json(&format!(
                "history/historic-process-instances/{}",
                qv(process_instance_id)
            ))
            .await?;
        Ok(body.map(|b| b.get("endTime").is_some_and(|e| !e.is_null())))
    }

    /// One historic variable of an instance (e.g. `outcome`, `autoApprove`).
    pub async fn historic_variable(
        &self,
        process_instance_id: &str,
        name: &str,
    ) -> Result<Option<serde_json::Value>, KernelError> {
        let body = self
            .get_json(&format!(
                "history/historic-variable-instances?processInstanceId={}&variableName={}",
                qv(process_instance_id),
                qv(name)
            ))
            .await?
            .unwrap_or_default();
        Ok(Self::data_array(&body)
            .first()
            .and_then(|v| v.pointer("/variable/value"))
            .cloned())
    }

    /// Ids of the historic activities an instance passed (`start`, `decide`, `approved` …).
    pub async fn historic_activities(
        &self,
        process_instance_id: &str,
    ) -> Result<Vec<String>, KernelError> {
        let body = self
            .get_json(&format!(
                "history/historic-activity-instances?processInstanceId={}&size=100",
                qv(process_instance_id)
            ))
            .await?
            .unwrap_or_default();
        Ok(Self::data_array(&body)
            .iter()
            .filter_map(|a| {
                a.get("activityId")
                    .and_then(|i| i.as_str())
                    .map(str::to_owned)
            })
            .collect())
    }
}


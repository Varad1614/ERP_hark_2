        m.insert("b".to_owned(), serde_json::json!(3));
        m.insert("c".to_owned(), serde_json::json!(1.5));
        m.insert("d".to_owned(), serde_json::json!("x"));
        m.insert("e".to_owned(), serde_json::json!({"k": 1}));
